#!/usr/bin/env node
// Assembles the static front end that GitHub Pages serves (https://<owner>.github.io/djb/).
// Usage: node scripts/build-pages.js [outDir]   (default: _site)
// This is the single list of what ships to Pages. Server code, tests, docs, tooling and
// desktop-bridge files are deliberately left out. Every path in the app is relative, so the
// same files work under the /djb/ subpath without changes.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

// Individual files at the repo root.
const PAGES_FILES = [
  'index.html', 'offline.html', 'manifest.webmanifest', 'sw.js', 'window.js',
  'api_client.js', 'submission_upload.js', 'battle_modes.js', 'app.js', 'social.js',
  // Embeddable player that other sites can iframe (see embed.html).
  'embed.html', 'embed.js'
];
// Whole folders the browser loads.
const PAGES_DIRS = ['studio', 'judge', 'assets'];
// index.html always loads this git-ignored file. When it is absent (as on Pages) ship an empty
// placeholder so it doesn't 404 and the app runs in offline demo mode. Never put keys here.
const LOCAL_CONFIG = 'supabase-browser-config.local.js';
const LOCAL_CONFIG_PLACEHOLDER = [
  '// GitHub Pages build: no Supabase project or API server is configured, so the app runs in',
  '// offline demo mode. Generated by scripts/build-pages.js; never add keys here.',
  'window.DJ_BATTLE_SUPABASE_CONFIG = window.DJ_BATTLE_SUPABASE_CONFIG || {};',
  ''
].join('\n');

function rootCssFiles(){
  return fs.readdirSync(root).filter(name => name.endsWith('.css') && fs.statSync(path.join(root, name)).isFile()).sort();
}

function pagesFileList(){
  return [...PAGES_FILES, ...rootCssFiles()];
}

function copyDir(src, dest){
  fs.mkdirSync(dest, { recursive:true });
  for(const entry of fs.readdirSync(src, { withFileTypes:true })){
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if(entry.isDirectory()) copyDir(from, to);
    else if(entry.isFile()) fs.copyFileSync(from, to);
  }
}

function buildPages(outDir = path.join(root, '_site')){
  fs.rmSync(outDir, { recursive:true, force:true });
  fs.mkdirSync(outDir, { recursive:true });
  for(const file of pagesFileList()){
    const src = path.join(root, file);
    if(!fs.existsSync(src)) throw new Error(`build-pages: missing ${file}`);
    fs.copyFileSync(src, path.join(outDir, file));
  }
  for(const dir of PAGES_DIRS){
    const src = path.join(root, dir);
    if(!fs.existsSync(src)) throw new Error(`build-pages: missing folder ${dir}/`);
    copyDir(src, path.join(outDir, dir));
  }
  const localConfig = path.join(root, LOCAL_CONFIG);
  if(fs.existsSync(localConfig)) fs.copyFileSync(localConfig, path.join(outDir, LOCAL_CONFIG));
  else fs.writeFileSync(path.join(outDir, LOCAL_CONFIG), LOCAL_CONFIG_PLACEHOLDER);
  fs.writeFileSync(path.join(outDir, '.nojekyll'), '');
  return outDir;
}

module.exports = { PAGES_FILES, PAGES_DIRS, LOCAL_CONFIG, pagesFileList, buildPages };

if(require.main === module){
  const out = buildPages(process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  console.log(`Pages site assembled in ${path.relative(process.cwd(), out) || '.'}`);
}
